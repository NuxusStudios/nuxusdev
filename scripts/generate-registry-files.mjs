/** Emits the TypeScript that wires imported components into the app. */
import { readFile, writeFile } from "node:fs/promises"
import path from "node:path"

const ROOT = process.cwd()
const { records } = JSON.parse(await readFile(path.join(ROOT, ".import-cache/result.json"), "utf8"))
records.sort((a, b) => a.slug.localeCompare(b.slug))

// ── lazy preview map ────────────────────────────────────────────────────
const imports = records
  .map((r) => `  ${JSON.stringify(r.slug)}: dynamic(() => import("./imported/demos/${r.slug}")),`)
  .join("\n")

await writeFile(
  path.join(ROOT, "src/registry/imported.ts"),
  `import dynamic from "next/dynamic"
import type { ComponentType } from "react"

/**
 * Generated by scripts/generate-registry-files.mjs — do not edit by hand.
 * Components imported from public MIT shadcn registries.
 */
export const IMPORTED_REGISTRY: Record<string, ComponentType> = {
${imports}
}
`
)

// ── component records ───────────────────────────────────────────────────
const serialize = (r) => `  {
    id: ${JSON.stringify(r.id)},
    slug: ${JSON.stringify(r.slug)},
    name: ${JSON.stringify(r.name)},
    description: ${JSON.stringify(r.description)},
    authorHandle: ${JSON.stringify(r.authorHandle)},
    librarySlug: ${JSON.stringify(r.librarySlug)},
    tags: ${JSON.stringify(r.tags)},
    previewKey: ${JSON.stringify(r.previewKey)},
    fileName: ${JSON.stringify(r.fileName)},
    demoFileName: ${JSON.stringify(r.demoFileName)},
    dependencies: ${JSON.stringify(r.dependencies)},
    license: ${JSON.stringify(r.license)},
    source: ${JSON.stringify(r.source)},
    createdAt: ${JSON.stringify(r.createdAt)},
    bookmarks: ${r.bookmarks},
    views: ${r.views},
    installs: ${r.installs},${r.featured ? "\n    featured: true," : ""}
    previewBg: "dark",
    previewWidth: ${r.previewWidth},
    imported: true,
  },`

await writeFile(
  path.join(ROOT, "src/lib/data/imported-components.ts"),
  `import type { ComponentRecord } from "@/lib/types"

/**
 * Generated by scripts/generate-registry-files.mjs — do not edit by hand.
 *
 * Imported from public, MIT-licensed shadcn registries. Author, license and
 * source are carried through from the upstream registry, as MIT requires.
 * Engagement counts (bookmarks / views / installs) are generated from a stable
 * hash of the component name — this is a clone, there is no real telemetry.
 */
export const IMPORTED_COMPONENTS: ComponentRecord[] = [
${records.map(serialize).join("\n")}
]
`
)

const aliases = records
  .filter((r) => r.slug !== r.fileName.replace(/\.tsx?$/, ""))
  .map((r) => `  ${JSON.stringify(r.slug)}: ${JSON.stringify(r.fileName.replace(/\.tsx?$/, ""))},`)
  .join("\n")

await writeFile(
  path.join(ROOT, "src/lib/data/import-aliases.ts"),
  `/**
 * Generated by scripts/generate-registry-files.mjs — do not edit by hand.
 *
 * Imported components are stored under a prefixed key when their name collides
 * with one already in the registry. The code viewer maps them back so the
 * import path shown is the one a consumer would actually write.
 */
export const IMPORT_ALIASES: Record<string, string> = {
${aliases}
}
`
)

const byLibrary = {}
for (const r of records) byLibrary[r.librarySlug] = (byLibrary[r.librarySlug] ?? 0) + 1
console.log("wrote", records.length, "records", byLibrary)
