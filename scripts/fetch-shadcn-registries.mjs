#!/usr/bin/env node
/**
 * Snapshots the official shadcn registry index into src/lib/data/registries.ts.
 *
 * The directory page reads the snapshot rather than the network, so a slow or
 * unavailable upstream can never slow down or break our page. Re-run it to
 * refresh: `npm run registries:fetch`.
 */
import { writeFileSync } from "node:fs"

const SOURCE = "https://ui.shadcn.com/r/registries.json"
const OUT = "src/lib/data/registries.ts"

const response = await fetch(SOURCE, { headers: { accept: "application/json" } })
if (!response.ok) {
  console.error(`[registries] ${SOURCE} returned ${response.status}`)
  process.exit(1)
}

const raw = await response.json()
if (!Array.isArray(raw) || raw.length === 0) {
  console.error("[registries] unexpected payload shape")
  process.exit(1)
}

const entries = raw
  // a hidden entry is one the upstream index itself chooses not to show
  .filter((entry) => entry?.name && entry?.url && !entry.health?.hidden)
  .map((entry) => ({
    namespace: entry.name,
    homepage: entry.homepage ?? null,
    url: entry.url,
    description: (entry.description ?? "").trim(),
    status: entry.health?.status ?? "unknown",
    score: typeof entry.health?.score === "number" ? Math.round(entry.health.score) : null,
    availability30d:
      typeof entry.health?.availability30d === "number"
        ? Math.round(entry.health.availability30d * 1000) / 10
        : null,
  }))
  .sort((a, b) => (b.score ?? -1) - (a.score ?? -1) || a.namespace.localeCompare(b.namespace))

const file = `// Generated by scripts/fetch-shadcn-registries.mjs — do not edit by hand.
// Source: ${SOURCE}
// Snapshot taken: ${new Date().toISOString()}

export interface ShadcnRegistry {
  /** e.g. "@magicui" — usable as \`npx shadcn add @magicui/marquee\` */
  namespace: string
  homepage: string | null
  /** URL template, e.g. "https://magicui.design/r/{name}.json" */
  url: string
  description: string
  status: "healthy" | "degraded" | "observing" | "unavailable" | "unknown"
  /** upstream health score out of 100 */
  score: number | null
  /** uptime over the last 30 days, as a percentage */
  availability30d: number | null
}

export const REGISTRIES_SNAPSHOT_AT = "${new Date().toISOString()}"

export const REGISTRIES: ShadcnRegistry[] = ${JSON.stringify(entries, null, 2)}
`

writeFileSync(OUT, file)
console.log(`[registries] wrote ${entries.length} registries to ${OUT}`)
